/*
 * Практична робота №3. Режими роботи модуля TMR0.
 * PIC16F84A, Fosc = 4 МГц (1 машинний цикл = 1 мкс), XC8.
 *
 * 3.1 TMR0 від Fosc/4 без дільника: відлік 200 імпульсів.
 * 3.2 Без дільника: сигнал на RB0, T = 220 мс (1 — 20 мс, 0 — 200 мс).
 * 3.3 З дільником 1:256: прапорець T0IF кожні 50 мс.
 * 3.4 З дільником: часовий інтервал 500 мс (10 × 50 мс).
 */

#include <xc.h>

#pragma config FOSC = XT, WDTE = OFF, PWRTE = OFF, CP = OFF

// Після запису в TMR0 інкремент затримується на 2 цикли:
// інтервал = 2 + (256 - N) циклів.
#define TMR0_200US  58      // 2 + (256 - 58)  = 200 імпульсів
#define TMR0_50MS   61      // (256 - 61) * 256 = 49 920 мкс
// Крок 200 мкс у циклі: ще ~20 циклів займає сам цикл,
// тому TMR0 заряджається на 20 більше (виміряно Stopwatch)
#define TMR0_STEP   (TMR0_200US + 20)

//---- 3.1 / 3.2: TMR0 без попереднього дільника ----
void tmr0_no_prescaler(void)
{
    // T0CS = 0 — тактування від Fosc/4;
    // PSA = 1 — дільник віддано WDT, тож TMR0 рахує 1:1
    OPTION_REG = 0b10001000;
    INTCON = 0;                 // переривання вимкнено, T0IF = 0
}

// Відлік 200 імпульсів Fosc/4 (200 мкс) з очікуванням T0IF
void count_200(void)
{
    TMR0 = TMR0_200US;
    T0IF = 0;
    while (!T0IF)
        ;
}

//---- 3.3 / 3.4: TMR0 з попереднім дільником 1:256 ----
void tmr0_prescaler_256(void)
{
    // T0CS = 0, PSA = 0 — дільник на TMR0, PS2:PS0 = 111 (1:256)
    OPTION_REG = 0b10000111;
    INTCON = 0;
}

// Встановлення T0IF через 50 мс
void wait_50ms(void)
{
    TMR0 = TMR0_50MS;           // запис також обнуляє дільник
    T0IF = 0;
    while (!T0IF)
        ;
}

// Інтервал 500 мс = 10 переповнень по 50 мс
void wait_500ms(void)
{
    for (unsigned char n = 0; n < 10; n++)
        wait_50ms();
}

// Затримка n × 200 мкс без дільника (для сигналу на RB0)
void delay_200us(unsigned int n)
{
    while (n--)
    {
        TMR0 = TMR0_STEP;
        T0IF = 0;
        while (!T0IF)
            ;
    }
}

void main(void)
{
    TRISB0 = 0;                 // RB0 — вихід сигналу
    RB0 = 0;

    //---- 3.1: 200 імпульсів ----
    tmr0_no_prescaler();
    count_200();

    //---- 3.3: прапорець T0IF через 50 мс ----
    tmr0_prescaler_256();
    wait_50ms();

    //---- 3.4: інтервал 500 мс ----
    wait_500ms();

    //---- 3.2: сигнал на RB0, T = 220 мс ----
    tmr0_no_prescaler();
    while (1)
    {
        RB0 = 1;
        delay_200us(100);       // 100 × 200 мкс = 20 мс
        RB0 = 0;
        delay_200us(1000);      // 1000 × 200 мкс = 200 мс
    }
}
